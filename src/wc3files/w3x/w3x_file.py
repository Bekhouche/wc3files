class W3xReadMode(Enum):
     """How far `W3xFile.read()` goes into an archive.

     SIMPLE   - look up `(listfile)` and stop. Missing listfile → `protected`,
                no member extract, no name scan.
     LISTFILE - extract every file the listfile names. Missing listfile →
                `protected` and stop. Default: a map without a listfile is
                protected, not a prompt to recover it.
     DEEP     - when there is no usable listfile, probe the bundled name list
                and walk references until nothing new turns up. Opt-in; this
                is the minutes-long recovery path, not the ordinary read.
     """
     SIMPLE = 'simple'
     LISTFILE = 'listfile'
     DEEP = 'deep'


class W3xFile(object):
     # Script files that may reference other map assets by path.
     SCRIPT_FILES = ['war3map.j', 'war3map.lua', 'scripts\\war3map.j', 'scripts\\war3map.lua']
     # Object data files (and their Reforged HD "Skin" overrides) that may reference model/icon/sound paths.
     OBJECT_FILE_EXTENSIONS = ['w3u', 'w3t', 'w3b', 'w3d', 'w3a', 'w3h', 'w3q']
     OBJECT_FILES = ['war3map.' + ext for ext in OBJECT_FILE_EXTENSIONS] + \
                    ['war3mapSkin.' + ext for ext in OBJECT_FILE_EXTENSIONS]
     # Extensions commonly referenced (by string literal) from WC3 map scripts, object data, and text manifests.
     SCRIPT_ASSET_EXTENSIONS = ['.mdl', '.mdx', '.blp', '.dds', '.tga', '.toc', '.wav', '.mp3', '.ai', '.fdf', '.txt']

     def __init__(self):

          self.initialize_crypt_table()
          self.clear()
          self.default_files = self.get_filelist()
     
     def clear(self):
          self.files = {}
          self._data = {'INFO': {}, 'HEADER': {}, 'HASH_TABLE': [], 'BLOCK_TABLE': []}
          self._temp = {}
          self.current_path = ''
          self.current_name = ''
          self.protected = False

     def export(self, path):
          if not os.path.exists(os.path.join(path, self.current_name)):
               os.mkdir(os.path.join(path, self.current_name))

          for file in self.files:
               if len(file.split('\\')) > 1:
                    if not os.path.exists(os.path.basename(os.path.join(path, self.current_name, file))):
                         os.makedirs(os.path.dirname(os.path.join(path, self.current_name, file)), exist_ok=True)
               f = open(os.path.join(path, self.current_name, file), 'wb')
               f.write(self.files[file] or b'')
               f.close()

     # Both are per-block-table-index metadata (checksums/timestamps for '(attributes)', a
     # digital signature for '(signature)') computed against the EXACT block table this
     # package's own MpqWriter builds - which depends on file order, sizes, and count. A copy
     # of either file from some other archive (e.g. re-packing a directory whose contents
     # were edited after being exported from a different .w3x) describes a block table that
     # no longer matches the one actually being written, and carrying it through verbatim
     # produces an archive whose attributes table itself is corrupt relative to its own block
     # table - confirmed as a real, severe bug: a real WC3 client crashed loading a repacked
     # map before it even reached the map-loading screen, with this the only structural
     # difference from a map the same client already opens fine. Neither is regenerated by
     # this package (documented in TODO.md as not implemented) - the safe, standard behavior
     # community map tools use for a custom-built archive is to omit them entirely, which the
     # game and World Editor both tolerate (no per-file integrity check at all is normal for a
     # simple custom map), rather than propagate one that's actively wrong.
     _STALE_ON_REPACK = ('(listfile)', '(attributes)', '(signature)')

     def build(self, src_path, dst_path, protection=MpqProtectionLevel.NONE, attributes=False):
          """Repack a directory previously produced by export() (or laid out the same way) into a .w3x archive."""
          files = {}
          for path_, _, filenames in os.walk(src_path):
               for filename in filenames:
                    full_path = os.path.join(path_, filename)
                    rel_path = os.path.relpath(full_path, src_path).replace(os.sep, '\\')
                    if rel_path in self._STALE_ON_REPACK:
                         continue
                    with open(full_path, 'rb') as handle:
                         files[rel_path] = handle.read()

          self.build_from_files(files, dst_path, protection=protection, attributes=attributes)

     def build_from_files(self, files, dst_path, sector_size_shift=3,
                           protection=MpqProtectionLevel.NONE, attributes=False):
          """Build a .w3x archive directly from a {filename: bytes} table, e.g. self.files after read()+edits.

          `protection` (see wc3files.mpq.data.MpqProtectionLevel / mpq/protection.py) opts into
          MPQ-container "protection" techniques real map protectors use - NONE (default) keeps the
          plain, standard archive layout. `attributes` (bool) additionally writes a real,
          freshly-computed `(attributes)` file matching this exact build - safe by construction
          (unlike carrying one forward from a different build, see `_STALE_ON_REPACK` above)."""
          MpqWriter(sector_size_shift=sector_size_shift, protection=protection,
                    attributes=attributes).write(files, dst_path)

     def read(self, file_path, mode=W3xReadMode.LISTFILE):
          """Read a `.w3x`/`.w3m`/`.w3n`. See `W3xReadMode` for `mode`.

          Default is LISTFILE: use the archive's own `(listfile)`, and if it
          is missing mark `self.protected` and stop. Pass `mode=DEEP` only
          when you actually want to recover a protected map.
          """
          if not isinstance(mode, W3xReadMode):
               mode = W3xReadMode(mode)
          self.clear()
          self.current_path = file_path
          self.current_name = os.path.basename(file_path).replace('.' + file_path.split('.')[-1], '')

          file_type = file_path.split('.')[-1].lower()
          if file_type not in [item.value for item in MapFileType]:
               raise ValueError(f"Invalid map/campaign file type: {file_type}")

          with BinaryFile(file_path, 'read') as reader:
               self.read_header(reader)
               self.read_hash_table(reader)
               self.read_block_table(reader)

               listfile = self.read_file(reader, '(listfile)')
               self.files['(listfile)'] = listfile
               names = []
               if listfile:
                    for line in listfile.splitlines():
                         name = line.decode('utf8', 'replace').strip()
                         if name:
                              names.append(name)

               if not names:
                    self.protected = True
                    if mode is W3xReadMode.DEEP:
                         self.read_without_listfile(reader)
                    return

               self.protected = False
               if mode is W3xReadMode.SIMPLE:
                    return
               for name in names:
                    data = self.read_file(reader, name)
                    if data is not None:
                         self.files[name] = data

     def read_without_listfile(self, reader):
          # No usable (listfile): probe known default names, then deep-scan - any
          # text-bearing or structured file already found (script, object data, SLK,
          # TXT, MDL/MDX) can itself name further real files, and a newly-found file
          # can name still more, so keep scanning until a pass turns up nothing new.
          #
          # The scan-candidate test and the per-file reference extraction are
          # deliberately imported from wc3files.mpq.files rather than reimplemented
          # here: this class carries its own MPQ primitives (crypt table, hash table,
          # read_file) but the *discovery logic* is the same problem MpqFiles solves,
          # and keeping two copies is exactly how this one silently fell behind (it
          # ran a fixed two manifest passes instead of iterating to a fixed point, and
          # never scanned models structurally at all).
          for file in tqdm(self.default_files):
               file_data = self.read_file(reader, file)
               if file_data:
                    self.files[file] = file_data

          for file in self.OBJECT_FILES:
               if file not in self.files:
                    file_data = self.read_file(reader, file)
                    if file_data:
                         self.files[file] = file_data

          scanned = set()
          while True:
               pending = [name for name in list(self.files.keys())
                          if name not in scanned and self.files.get(name)
                          and is_scan_candidate(name)]
               if not pending:
                    break

               candidates = set()
               for file in tqdm(pending):
                    scanned.add(file)
                    candidates |= extract_references(file, self.files[file])

               found_new = False
               for candidate in candidates:
                    if candidate not in self.files:
                         file_data = self.read_file(reader, candidate)
                         if file_data:
                              self.files[candidate] = file_data
                              found_new = True
               if not found_new:
                    break

     def find_script_referenced_files(self, reader):
          # Scan war3map.j/war3map.lua for quoted paths to other map assets (.mdx, .blp, .ai, ...).
          pattern = r'"([^"]+\.(?:' + '|'.join(ext[1:] for ext in self.SCRIPT_ASSET_EXTENSIONS) + r'))"'
          referenced = set()

          for script_file in self.SCRIPT_FILES:
               data = self.files.get(script_file) or self.read_file(reader, script_file)
               if not data:
                    continue
               self.files[script_file] = data
               text = data.decode('utf8', errors='ignore')
               referenced.update(match.replace('\\\\', '\\') for match in re.findall(pattern, text, re.IGNORECASE))

          return referenced

     def find_object_referenced_files(self, reader):
          # Parse war3map.w3u/w3t/.../war3mapSkin.w3u/... and pull any field value that looks like
          # a path to a model/icon/sound asset (e.g. a unit's model or portrait icon path).
          referenced = set()

          for object_file in self.OBJECT_FILES:
               data = self.files.get(object_file) or self.read_file(reader, object_file)
               if not data:
                    continue
               self.files[object_file] = data

               try:
                    obj = ObjectFile()
                    obj.read(data, object_file.split('.')[-1])
                    referenced.update(self._find_asset_paths(obj.export_data()))
               except Exception:
                    continue

          return referenced

     def find_manifest_referenced_files(self):
          # Mine Units\*.txt / *.slk and other text manifests for asset paths.
          # WC3 profile lines look like Art=path.blp,path2.tga — the path must start after
          # '=', / ',' / quotes, not include the field name (old pattern matched "Art=...").
          referenced = set()

          for name, data in list(self.files.items()):
               lowered = name.lower()
               if not data or not (lowered.endswith('.txt') or lowered.endswith('.slk')):
                    continue
               text = data.decode('utf8', errors='ignore')
               referenced.update(self._extract_manifest_asset_paths(text))

          return referenced

     def find_txt_referenced_files(self):
          # Back-compat alias used by callers/tests.
          return self.find_manifest_referenced_files()

     @classmethod
     def _extract_manifest_asset_paths(cls, text):
          ext_alt = '|'.join(ext[1:] for ext in cls.SCRIPT_ASSET_EXTENSIONS)
          pattern = rf'(?:^|[=,\s"\'])([^\s"\'=,]+\.(?:{ext_alt}))'
          return {match.replace('\\\\', '\\') for match in re.findall(pattern, text, re.IGNORECASE)}

     def _find_asset_paths(self, data):
          found = set()

          def walk(node):
               if isinstance(node, dict):
                    for value in node.values():
                         walk(value)
               elif isinstance(node, (list, tuple)):
                    for item in node:
                         walk(item)
               elif isinstance(node, str):
                    lowered = node.lower()
                    if any(lowered.endswith(ext) for ext in self.SCRIPT_ASSET_EXTENSIONS):
                         found.add(node)

          walk(data)
          return found

     def read_header(self, reader):
          magic = reader.read(BinaryDataType.BYTES)
          reader.seek(0)

          if magic == b'MPQ\x1a':
               data = reader.read(BinaryDataType.BYTES, num=32)
               self._data['HEADER'] = dict(zip([field.value for field in MPQFileHeaderFields], struct.unpack('<4s2I2H4I', data)))

               if self._data['HEADER']['FormatVersion'] == 1:
                    data = reader.read(BinaryDataType.BYTES, num=12)
                    extended_header = dict(zip([field.value for field in MPQFileHeaderExtendedFieldsFormatV2], struct.unpack('q2h', data)))
                    self._data['HEADER'].update(extended_header)

               self._data['HEADER']['ArchiveOffset'] = 0
          elif magic == b'HM3W':
               self._data['INFO']['MAGIC'] = reader.read(BinaryDataType.BYTES, num=4)
               self._data['INFO']['UNKNOWN'] = reader.read(BinaryDataType.BYTES, num=4)
               self._data['INFO']['MAP_NAME'] = reader.read(BinaryDataType.STRING)
               self._data['INFO']['MAP_FLAGS'] = reader.read(BinaryDataType.INT, num=4)
               self._data['INFO']['MAX_PLAYERS'] = reader.read(BinaryDataType.INT, num=4)

               reader.seek(512)
               magic = reader.read(BinaryDataType.BYTES)
               reader.seek(512)

               data = reader.read(BinaryDataType.BYTES, num=32)
               self._data['HEADER'] = dict(zip([field.value for field in MPQFileHeaderFields], struct.unpack('<4s2I2H4I', data)))

               if self._data['HEADER']['FormatVersion'] == 1:
                    data = reader.read(BinaryDataType.BYTES, num=12)
                    extended_header = dict(zip([field.value for field in MPQFileHeaderExtendedFieldsFormatV2], struct.unpack('q2h', data)))
                    self._data['HEADER'].update(extended_header)

               self._data['HEADER']['ArchiveOffset'] = 512
          else:
               raise ValueError("Invalid file header.!")
     
     def read_hash_table(self, reader):
          self._data['HASH_TABLE'] = []
          key = self.hash(MPQKeyType.MPQ_HASH_TABLE.value, MPQHashType.MPQ_HASH_FILE_KEY)
          
          reader.seek(self._data['HEADER']['HashTableOffset'] + self._data['HEADER']['ArchiveOffset'])

          data = self.decrypt(reader.read(BinaryDataType.BYTES, num=16*self._data['HEADER']['HashTableEntries']), key)
          for i in range(self._data['HEADER']['HashTableEntries']):
               entry = dict(zip([field.value for field in MPQHashTableEntry], struct.unpack('<2IHHI', data[i*16:i*16+16])))
               self._data['HASH_TABLE'].append(entry)

     def read_block_table(self, reader):
          self._data['BLOCK_TABLE'] = []
          
          key = self.hash(MPQKeyType.MPQ_BLOCK_TABLE.value, MPQHashType.MPQ_HASH_FILE_KEY)

          reader.seek(self._data['HEADER']['BlockTableOffset'] + self._data['HEADER']['ArchiveOffset'])

          data = self.decrypt(reader.read(BinaryDataType.BYTES, num=16*self._data['HEADER']['BlockTableEntries']), key)
          for i in range(self._data['HEADER']['BlockTableEntries']):
               entry = dict(zip([field.value for field in MPQBlockTableEntry], struct.unpack('<4I', data[i*16:i*16+16])))
               self._data['BLOCK_TABLE'].append(entry)

     def read_file(self, reader, filename):
          force_decompress = False
          hash_entry = self.get_hash_table_entry(filename)
          if hash_entry is None:
               return None
          
          #if hash_entry['FileBlockIndex'] > len(self._data['BLOCK_TABLE']):
          #     return None
          
          block_entry = self._data['BLOCK_TABLE'][hash_entry['FileBlockIndex']]

          if block_entry['Flags'] & MPQFileDataType.EXISTS.value:
               if block_entry['BlockSize'] == 0:
                    return None

               offset = block_entry['BlockOffset'] + self._data['HEADER']['ArchiveOffset']

               if block_entry['Flags'] & MPQFileDataType.ENCRYPTED.value:
                    key = self.hash(os.path.basename(filename), MPQHashType.MPQ_HASH_FILE_KEY)
                    if block_entry['Flags'] & MPQFileDataType.FIX_KEY.value:
                         key = (key + block_entry['BlockOffset']) ^ block_entry['FileSize']

               if not block_entry['Flags'] & MPQFileDataType.SINGLE_UNIT.value:
                    sector_size = 512 << self._data['HEADER']['SectorSizeShift']
                    sectors = block_entry['FileSize'] // sector_size + 1
                    if block_entry['Flags'] & MPQFileDataType.SECTOR_CRC.value:
                         crc = True
                         sectors += 1
                    else:
                         crc = False

                    result = BytesIO()
                    sector_bytes_left = block_entry['FileSize']
                    # 'sectors' already spans every data sector including a trailing partial one
                    # (positions[-1] always lands on the block's true compressed end).
                    block_count = sectors

                    reader.seek(offset)
                    sectors_data = reader.read(BinaryDataType.BYTES, num=4*(sectors+1))
                    if block_entry['Flags'] & MPQFileDataType.ENCRYPTED.value:
                         sectors_data = self.decrypt(sectors_data, key - 1)
                    positions = struct.unpack('<%dI' % (sectors + 1), sectors_data)

                    current_offset = 0
                    if block_entry['Flags'] & MPQFileDataType.COMPRESS.value :
                         reader.seek(offset + positions[0])
                         raw_bytes_to_read = positions[block_count] - positions[0]
                    else:
                         raw_bytes_to_read = block_entry['FileSize']

                    file_data = reader.read(BinaryDataType.BYTES, num=raw_bytes_to_read)

                    for i in range(block_count):
                         expected_sector_size = min(sector_size, sector_bytes_left)
                         this_sector_size = expected_sector_size
                         if block_entry['Flags'] & MPQFileDataType.COMPRESS.value:
                              this_sector_size = positions[i+1] - positions[i]

                         sector = file_data[current_offset:current_offset + this_sector_size]
                         if block_entry['Flags'] & MPQFileDataType.ENCRYPTED.value:
                              sector = self.decrypt(sector, key + i)

                         # A sector is only actually compressed when its stored size is smaller
                         # than its decompressed size; otherwise it was stored raw (common for
                         # already-compressed media like .mp3/.blp) and must be used as-is.
                         if (block_entry['Flags'] & MPQFileDataType.COMPRESS.value and
                         (force_decompress or len(sector) < expected_sector_size)):
                              sector = self.decompress(sector)

                         sector_bytes_left -= len(sector)
                         result.write(sector)

                         current_offset += this_sector_size
                    file_data = result.getvalue()

               else:
                    reader.seek(offset)
                    file_data = reader.read(BinaryDataType.BYTES, num=block_entry['BlockSize'])

                    if (block_entry['Flags'] & MPQFileDataType.COMPRESS.value and
                         (force_decompress or block_entry['FileSize'] > block_entry['BlockSize'])):
                         file_data = self.decompress(file_data)
               
               return file_data

     def initialize_crypt_table(self):
          self.crypt_table = {}
          seed = 0x00100001

          for index1 in range(0x100):
               for index2 in range(index1, index1 + 0x500, 0x100):
                    seed = (seed * 125 + 3) % 0x2AAAAB
                    temp1 = (seed & 0xFFFF) << 0x10

                    seed = (seed * 125 + 3) % 0x2AAAAB
                    temp2 = (seed & 0xFFFF)

                    self.crypt_table[index2] = (temp1 | temp2)

     def encrypt(self, buffer, key):
          buffer_length = len(buffer)
          seed = 0xEEEEEEEE
          for i in range(0, buffer_length, 4):
               seed += self.crypt_table[0x400 + (key & 0xFF)]
               ch = ctypes.c_ulong.from_buffer_copy(buffer[i:i+4]).value ^ (key + seed)
               key = ((~key << 0x15) + 0x11111111) | (key >> 0x0B)
               seed = ctypes.c_ulong.from_buffer_copy(buffer[i:i+4]).value + seed + (seed << 5) + 3

               buffer[i:i+4] = ch.to_bytes(4, byteorder='little')
          
          return buffer

     def decrypt(self, buffer, key):
          seed1 = key
          seed2 = 0xEEEEEEEE
          result = BytesIO()

          for i in range(len(buffer) // 4):
               seed2 += self.crypt_table[0x400 + (seed1 & 0xFF)]
               seed2 &= 0xFFFFFFFF
               value = struct.unpack("<I", buffer[i*4:i*4+4])[0]
               value = (value ^ (seed1 + seed2)) & 0xFFFFFFFF

               seed1 = ((~seed1 << 0x15) + 0x11111111) | (seed1 >> 0x0B)
               seed1 &= 0xFFFFFFFF
               seed2 = value + seed2 + (seed2 << 5) + 3 & 0xFFFFFFFF

               result.write(struct.pack("<I", value))

          rem = len(buffer) % 4
          if rem:
               result.write(buffer[-rem:])

          return result.getvalue()
     
     def hash(self, lpszString, hash_type):
          seed1 = 0x7FED7FED
          seed2 = 0xEEEEEEEE

          # MPQ hashes the name's bytes, not its characters. Indexing the
          # crypt table by code point breaks the moment a name is not plain
          # ASCII: a real map here carries a listfile entry that does not
          # decode as UTF-8, so it arrived as U+FFFD and the lookup asked for
          # crypt_table[65789] and brought down the whole archive. Encoding
          # back to bytes keeps every index inside 0..255, and
          # surrogateescape returns the original byte when the name came from
          # a surrogateescape decode.
          if isinstance(lpszString, (bytes, bytearray)):
               raw = bytes(lpszString)
          else:
               try:
                    raw = lpszString.encode('cp1252', errors='surrogateescape')
               except UnicodeEncodeError:
                    raw = lpszString.encode('utf-8', errors='surrogateescape')

          for ch in raw.upper():
               value = self.crypt_table[(hash_type.value << 8) + (ch & 0xFF)]
               
               seed1 = (value ^ (seed1 + seed2)) & 0xFFFFFFFF
               seed2 = ch + seed1 + seed2 + (seed2 << 5) + 3 & 0xFFFFFFFF

          return seed1
     
     def get_hash_table_entry(self, filename, language=0, platform=0):
          hash_a = self.hash(filename, MPQHashType.MPQ_HASH_NAME_A)
          hash_b = self.hash(filename, MPQHashType.MPQ_HASH_NAME_B)
          best = None
          for entry in self._data['HASH_TABLE']:
               if (entry['FilePathHashA'] == hash_a and entry['FilePathHashB'] == hash_b):
                    if language == entry['Language'] and platform == entry['Platform']:
                         return entry
                    if (entry['Language'] == 0 or language == entry['Language']) and \
                         (entry['Platform'] == 0 or platform == entry['Platform']):
                         best = entry
          return best
     
     @staticmethod
     def decompress(data):
          """Decompresses a single MPQ sector: the first byte is a compression-method bitmask, the rest is the compressed payload."""
          compression_mask = data[0]
          if compression_mask == 0:
               return data[1:]

          decompressed_data = data[1:]

          if compression_mask & 0x01:  # Huffman encoded
               decompressed_data = decompressed_data
          if compression_mask & 0x02:  # Deflated (ZLib)
               decompressed_data = zlib.decompress(decompressed_data)
          if compression_mask & 0x08:  # Imploded (PKWare)
               import dclimplode  # optional native codec, rarely hit - keep it out of the module's hard dependencies
               decompressed_data = dclimplode.decompressobj().decompress(decompressed_data)
          if compression_mask & 0x10:  # BZip2 compressed
               decompressed_data = bz2.decompress(decompressed_data)

          return decompressed_data
          
